function isUCIClient() {
 try {
	var isLcpAvailable = window.parent.document.getElementById("ClientApiFrame_MARS") ? true : false;
	return isLcpAvailable || (window['Xrm'] && window['Xrm'].Internal.isUci());
	}
 catch(e){
	return false;
	}
}

function LoadedGuidedHelp() {
	// Do not proceed if on UCI
	if (isUCIClient()) {
		return false;
	}

    var isMarsEnabledForOrg = window['Xrm'].Internal.isFeatureEnabled("FCB.GuidedHelp");

    var isISHPage = window['Xrm'].Internal.isEnabledForInteractionCentric();

    var isMarsEnabledForUser = window['Xrm'].Internal.isGuidedHelpEnabledForUser();

    //If MARS FCB enabled
    if (isMarsEnabledForOrg && isMarsEnabledForUser && Xrm.Page.context.client.getClient() == Xrm.ClientName.mobile) {
        if (isISHPage) {
            if (!window['Xrm'].Internal.isFeatureEnabled("FCB.ISHGuidedHelp")) {
                showFCBWarning();
                return;
            }
            else if (window['Xrm'].Internal.isFeatureEnabled("FCB.MarsLegacyClientEnabled")) {
                showFCBWarning(true);
            }
        }
        localStorage.setItem("marsLoaderInitialized", "0");
        if (window['Xrm'].Page.context.isCrmOnline() && window['Xrm'].Internal.isFeatureEnabled("FCB.MarsLegacyClientEnabled")) {
            //MARS v1
            loadMars("https://go.microsoft.com/fwlink/?LinkID=746342");
        }
        else {
            //MARS v2
            loadMars("https://go.microsoft.com/fwlink/?linkid=784821");
        }
        if (isISHPage && window.localStorage.getItem('isMarsISHDashboard') == 'true') {
            enableGuidedHelp();
            window.localStorage.removeItem('isMarsISHDashboard');
        }
    }
        //MARS FCB disabled but sitemap clicked to launch content library
    else {
        showFCBWarning();
    }
}

function getWhitelistedPageTokens() {
    return ["pagetype", "id", "etn"];
}

function showFCBWarning() {
    if (localStorage.getItem("launchMARSDesigner") == "true") {
        var windowObj = window.parent;
        var alertString = new windowObj['Xrm'].AlertDialogStrings();
        alertString.text = islegacyClient ? window["MarsV1WarningString" + windowObj['Xrm'].Page.context.getUserLcid()] : window["FCBWarningString" + windowObj['Xrm'].Page.context.getUserLcid()];
        windowObj['Xrm'].Dialog.openAlertDialog(alertString, null, null);
        localStorage.removeItem("launchMARSDesigner");
    }
}


function checkForGuidedHelp() {
	if (isUCIClient()) {
		return false;
	}
    try {
        var windowObj = window.parent.document.getElementById("PersistentScriptsIFrame").contentWindow;
        windowObj["_MicrosoftMars"]["Client"]["Loader"]["MarsLoader"]["prototype"].loadRunnerAndDesigner();
    }
    catch (error) {
        if (retryCount < 3) {
            retryCount++;
            window.setTimeout(function () {
                checkForGuidedHelp();
            }, 1000);
        }
    }
}


//Enable rule for LearningPath commands for Moca
function enableGuidedHelp() {
	if (isUCIClient()) {
		return false;
	}
    var isISHPage = window['Xrm'].Internal.isEnabledForInteractionCentric();
    //Enable only for mobile client on tablet form factor.
    if (isISHPage || (Xrm.Page.context.client.getClient() == Xrm.ClientName.mobile && Xrm.Page.context.client.getFormFactor() == 2)) {
        var isMarsEnabledForUser = window['Xrm'].Internal.isGuidedHelpEnabledForUser();
        var marsScriptsDownloaded = localStorage.getItem("marsScriptsDownloaded");
        if (isMarsEnabledForUser && marsScriptsDownloaded == "1") {
            initializeMars();
            return !isISHPage; 
        }
    }
    return false;
} 

//Enable rule to disable LearningPath Content Library command for ISH and UCI
function isNotISH(){
	return !isUCIClient() && !window['Xrm'].Internal.isEnabledForInteractionCentric();
}

//Enable rule for LearningPath Content Library command for Moca
function enableLearningPathDesigner() {
	if (isUCIClient()) {
		return false;
	}
    if (!window.parent['Xrm'].Internal.isFeatureEnabled("FCB.MarsLegacyClientEnabled")) {
        var userAgent = window.parent["Microsoft"]["Crm"]["Client"]["Core"]["Framework"]["UserAgent"];
        if (userAgent) {
            return !userAgent["getInstance"]().get_PALEnabled();
        }
        return true;
    }
    return false;
}


function launchLPLibrary() {
	if (isUCIClient()) {
		return false;
	}
    try {
        var windowObj = window.parent.document.getElementById("PersistentScriptsIFrame").contentWindow;
        windowObj["_MicrosoftMars"]["Client"]["Loader"]["MarsLoader"]["prototype"].launchDesigner();
    }
    catch (err) {
        console.log("Error in launching Learning Path Library");
    }
}


function initializeMars() {
    if (localStorage.getItem("marsLoaderInitialized") != 1) {
        var windowObj = window.parent.document.getElementById("PersistentScriptsIFrame").contentWindow;
        if (windowObj["_MicrosoftMars"]) {
            localStorage.setItem("marsLoaderInitialized", "1");
            try {
                windowObj.marsLoader = new windowObj["_MicrosoftMars"].Client.Loader.MarsLoader(windowObj["_MicrosoftMars"]["Client"]["Designer"] && windowObj["_MicrosoftMars"]["Client"]["Designer"]["App"]["isDesignerLaunched"]);
            } catch (err) {
                console.log("Error in initialing Mars");
            }

        }
        else {
            window.setTimeout(function () {
                initializeMars();
            }, 1000);
        }
    }
}



